    public function run(): void
    {
        if (Setting::getValue('article_import_v1') === true) {
            return;
        }

        $sanitizer = app(HtmlSanitizer::class);
        $images = app(ImageProcessor::class);

        foreach ($this->articles() as $article) {
            $slug = Slugger::fromTitle($article['title']);
            if (Article::query()->where('slug', $slug)->exists()) {
                continue;
            }

            Article::query()->create([
                'title' => $article['title'],
                'slug' => Slugger::unique($article['title']),
                'excerpt' => $article['excerpt'],
                'content' => $sanitizer->clean($article['content']),
                'image' => $this->image($images, $article['image'], $article['title']),
                'is_published' => true,
                'published_at' => Carbon::parse($article['published_at']),
            ]);
        }

        Setting::putValue('article_import_v1', true);
    }

    /**
     * @return array{original: string, webp: array<string, string>, alt: string}
     */
    private function image(ImageProcessor $images, string $filename, string $alt): array
    {
        $path = __DIR__.'/assets/articles/'.$filename;
        $file = new UploadedFile($path, $filename, 'image/png', null, true);
        $stored = $images->store($file);
        $stored['alt'] = $alt;

        return $stored;
    }

